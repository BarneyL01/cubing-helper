// Orozco step 2 (owner's request 2026-11-08): pairs with P done in one commutator, the way Orozco does pairs with B.
//   2a: three bases [R U R' , D / D' / D2] (positions L, T, H) - P stays put under L turns, like B under D/L turns.
//       Letters into L: L (none), D (L), R (L2), X (L'); into T: T; into H: H, G (L), F (L2), E (L').
//   2b: two more bases [R' D' R , U2] (A) and [R' D' R , U'] (D): P with A or D; P with I, S, U (L', L, L2 into A);
//       A or D with L, T, H (D, D', D2 into P).
// As written (insertion first) a base solves P then the letter (2a) or A/D then P (2b); halves swapped = reverse.
// Every entry is checked: it cycles C -> 1st -> 2nd -> C and moves nothing else; setups never move the buffer, and
// move only one target.
//   node log/2026-11-08-orozco-step2.mjs           checks; prints ALL OK
//   node log/2026-11-08-orozco-step2.mjs --write   also rewrites data/orozco-step2.js
import { writeFileSync } from 'node:fs';
import { permOf, spotOf, spots, expandBrackets, cancelMoves } from './three-style-lib.mjs';
import { applyAlg, solvedCube } from '../js/cube-sim.js';

const fails = [];
const check = (n, ok) => { if (!ok) fails.push(n); };
const key = (s) => `${s.p.join()}|${s.n.join()}`;
const K = (l) => key(solvedCube()[spotOf(l)]);

// [base, insertion, interchange, the base's own pair (insertion first), letters: [letter, setup]]
const PLAN = [
  { step: '2a', ins: "R U R'", inter: 'D', pos: 'L', fixed: 'P', letters: [['L', ''], ['D', 'L'], ['R', 'L2'], ['X', "L'"]] },
  { step: '2a', ins: "R U R'", inter: "D'", pos: 'T', fixed: 'P', letters: [['T', '']] },
  { step: '2a', ins: "R U R'", inter: 'D2', pos: 'H', fixed: 'P', letters: [['H', ''], ['G', 'L'], ['F', 'L2'], ['E', "L'"]] },
  { step: '2b', ins: "R' D' R", inter: 'U2', pos: 'A', fixed: 'P', letters: [['A', ''], ['I', "L'"], ['S', 'L'], ['U', 'L2']] },
  { step: '2b', ins: "R' D' R", inter: 'U2', pos: 'P', fixed: 'A', letters: [['L', 'D'], ['T', "D'"], ['H', 'D2']] },
  { step: '2b', ins: "R' D' R", inter: "U'", pos: 'P', fixed: 'D', letters: [['L', 'D'], ['T', "D'"], ['H', 'D2']] },
];

const entries = [];
const cycleOf = (alg) => { const p = permOf(expandBrackets(alg)); const C = spotOf('C'); return [p[C], p[p[C]]]; };
for (const b of PLAN) {
  for (const [core, insFirst] of [[`[${b.ins} , ${b.inter}]`, true], [`[${b.inter} , ${b.ins}]`, false]]) {
    for (const [x, setup] of b.letters) {
      // the base on its own cycles buffer -> u -> v; with the setup, the letter x takes the place of pos
      const notation = setup ? `[${setup} : ${core}]` : core;
      const moves = cancelMoves(expandBrackets(notation));
      const st = applyAlg(solvedCube().map((s) => ({ ...s, home: key(s) })), moves);
      const where = new Map(st.map((s) => [s.home, key(s)]));
      // read the pair from the moves: buffer goes to first, first to second
      const letters = Object.keys({ A: 1, B: 1, D: 1, E: 1, F: 1, G: 1, H: 1, I: 1, K: 1, L: 1, N: 1, O: 1, P: 1, Q: 1, R: 1, S: 1, T: 1, U: 1, V: 1, W: 1, X: 1 });
      const first = letters.find((l) => where.get(K('C')) === K(l));
      const second = letters.find((l) => where.get(K(first)) === K(l));
      check(`${notation} is a 3-cycle with the buffer`, first && second && where.get(K(second)) === K('C') && st.filter((s) => s.home !== key(s)).length === 9);
      const want = new Set([x, b.fixed]);
      check(`${notation} solves ${x} and ${b.fixed}`, want.has(first) && want.has(second) && first !== second);
      if (setup) {
        const sp = permOf(setup);
        check(`${setup} keeps the buffer`, sp[spotOf('C')] === spotOf('C'));
        check(`${setup} keeps ${b.fixed}`, sp[spotOf(b.fixed)] === spotOf(b.fixed));
        check(`${setup} moves ${x} into ${b.pos}`, sp[spotOf(x)] === spotOf(b.pos));
      }
      const pair = first + second;
      check(`${pair} once`, !entries.some((e) => e.pair === pair));
      entries.push({ pair, first, second, notation, setup, core, insertion: b.ins, interchange: b.inter, spots: spots(first, second, setup, core),
        setupMoves: setup ? setup.split(' ').length : 0, moves, count: moves.split(' ').length, kind: 'one', step: b.step,
        base: `${b.fixed}${b.pos}`, fixed: b.fixed, pos: b.pos, insFirst });
    }
  }
}
check('18 pairs in 2a', entries.filter((e) => e.step === '2a').length === 18);
check('38 pairs in all', entries.length === 38);
for (const s of ['2a', '2b']) { const l = entries.filter((e) => e.step === s); console.log(`${s}: ${l.length} pairs, mean ${(l.reduce((a, e) => a + e.count, 0) / l.length).toFixed(1)} moves, max ${Math.max(...l.map((e) => e.count))}`); }
if (process.argv.includes('--write') && !fails.length) {
  writeFileSync(new URL('../data/orozco-step2.js', import.meta.url),
    `// BEGIN GENERATED\n// GENERATED by log/2026-11-08-orozco-step2.mjs --write. Do not edit by hand.\n// Orozco step 2: pairs with P (and A/D with L, T, H) in one commutator; setups of one L or D turn at most.\nexport const orozcoStep2 = ${JSON.stringify(entries).replace(/\},\{/g, '},\n{')};\n// END GENERATED\n`);
  console.log('wrote data/orozco-step2.js');
}
console.log(fails.length ? `FAIL\n${fails.slice(0, 20).join('\n')}` : 'ALL OK');
