// 8355 last five corners (cube held with the four unsolved corners in the bottom layer and the fifth at
// UFR, every edge solved): can one or two "move the corners" sequences plus the corner-twist algorithm
// solve every position? Permute first (ignoring twist), then twist.
//   node log/2026-10-22-l5c-tools.mjs
import { PIECES, makeMoves, solvedState, apply, isHome } from './2026-10-22-sim-engine.mjs';
const x = (w, k) => Array(k).fill(w).join(' ');
const inv = (alg) => alg.split(' ').reverse().map((t) => (t.endsWith("'") ? t[0] : t.endsWith('2') ? t : `${t}'`)).join(' ');
const FIVE = ['UFR', 'DFR', 'DFL', 'DBL', 'DBR'];
const five = PIECES.filter((p) => FIVE.includes(p.name));
const others = PIECES.filter((p) => !FIVE.includes(p.name));
const D = ['', 'D', 'D2', "D'"];
const conj = (a, alg) => (a ? `${a} ${alg} ${inv(a)}` : alg);

const PERMUTERS = {
  'Sassy x3 twice, with a bottom turn between: (Sassy)x3 D (Sassy)x3 D\'': (d) => `${x("R U R' U'", 3)} ${d} ${x("R U R' U'", 3)} ${inv(d)}`,
  "(D2 L U2 L')x2": () => x("D2 L U2 L'", 2),
};
const TWISTS = [];
for (const d of ['D', 'D2', "D'"]) {
  TWISTS.push(`${x("R U R' U'", 2)} ${d} ${x("U R U' R'", 2)} ${inv(d)}`);
  TWISTS.push(`${x("U R U' R'", 2)} ${d} ${x("R U R' U'", 2)} ${inv(d)}`);
}
const check = (alg) => {
  const st = apply(solvedState(), makeMoves([{ name: 'a', alg, family: 'a' }])[0].perm);
  return { others: others.every((p) => isHome(st, p)), moved: five.filter((p) => !isHome(st, p)).map((p) => p.name) };
};
for (const [n, f] of Object.entries(PERMUTERS)) {
  for (const d of ['D', 'D2', "D'"]) {
    const alg = f(d);
    const c = check(alg);
    console.log(`${n} [${d}]: ${alg.split(' ').length} turns; only the five corners: ${c.others}; moves ${c.moved.join(' ')}`);
    if (!n.includes('twice')) break;
  }
}
for (const t of TWISTS) { const c = check(t); if (!c.others) console.log('twist touches others!', t); }

// position key: where each of the five corners is, and its twist
const key = (st) => five.map((p) => p.ids.map((i) => st[i]).join('.')).join('|');
const permKey = (st) => five.map((p) => Math.min(...p.ids.map((i) => st[i]))).join('|'); // ignores twist (min sticker id identifies the slot)
function bfs(gens, keyFn) {
  const start = solvedState();
  const dist = new Map([[keyFn(start), 0]]);
  let frontier = [start];
  for (let d = 1; frontier.length; d++) {
    const next = [];
    for (const s of frontier) for (const g of gens) {
      const n = apply(s, g.perm); const k = keyFn(n);
      if (!dist.has(k)) { dist.set(k, d); next.push(n); }
    }
    frontier = next;
  }
  return dist;
}
const hist = (m) => { const h = {}; for (const v of m.values()) h[v] = (h[v] ?? 0) + 1; return JSON.stringify(h); };
// R' brings the UFR corner down to DFR, so R' (twist) R twists UFR and a bottom corner
const twistGens = makeMoves(TWISTS.flatMap((t) => [...D.map((a) => conj(a, t)), conj("R'", t)]).map((alg, i) => ({ name: `t${i}`, alg, family: `t${i}` })));
for (const [n, f] of Object.entries(PERMUTERS)) {
  const base = n.includes('twice') ? ['D', 'D2', "D'"].map(f) : [f()];
  const algs = base.flatMap((b) => [b, inv(b)]).flatMap((b) => D.map((a) => conj(a, b)));
  const gens = makeMoves(algs.map((alg, i) => ({ name: `p${i}`, alg, family: `p${i}` })));
  const perm = bfs(gens, permKey);
  const all = bfs([...gens, ...twistGens], key);
  console.log(`\n${n} (with bottom-turn setups) + the Sassy twist:`);
  console.log(`  arrangements of the five corners reached (twist ignored): ${perm.size} of 60; sequences needed: ${hist(perm)}`);
  console.log(`  full positions reached: ${all.size} of 4860; algorithms needed (moving or twisting): ${hist(all)}`);
}
const tw = bfs(twistGens, key);
console.log(`\nTwist algorithm alone, corners already in place: ${tw.size} of 81 twist patterns; algorithms needed: ${hist(tw)}`);

// two phases, as a solver would: (1) move the corners to their places with the fewest movers,
// (2) twist with the fewest twists. Count both for every one of the 4860 positions.
for (const [n, f] of Object.entries(PERMUTERS)) {
  const base = n.includes('twice') ? ['D', 'D2', "D'"].map(f) : [f()];
  const algs = base.flatMap((b) => [b, inv(b)]).flatMap((b) => D.map((a) => conj(a, b)));
  const gens = makeMoves(algs.map((alg, i) => ({ name: `p${i}`, alg, family: `p${i}`, len: alg.split(' ').length })));
  // BFS from solved over movers gives, for each arrangement, a shortest mover sequence (as states)
  const twistDist = bfs(twistGens, key);
  // enumerate all positions: apply movers/twists from solved (BFS over everything), then solve in two phases
  const all = bfs([...gens, ...twistGens], key);
  // phase 1 distances by arrangement, with a representative path: BFS from each position is costly, so
  // use inverse reasoning: arrangement distance is the same from either side for a group generated by
  // sequences and their inverses
  const permDist = bfs(gens, permKey);
  const seenPos = new Map(); let frontier = [solvedState()]; seenPos.set(key(frontier[0]), frontier[0]);
  while (frontier.length) { const nx = []; for (const st of frontier) for (const g of [...gens, ...twistGens]) { const q = apply(st, g.perm); const k = key(q); if (!seenPos.has(k)) { seenPos.set(k, q); nx.push(q); } } frontier = nx; }
  const totals = {}; let worst = 0; let sum = 0; let turns = 0;
  for (const st of seenPos.values()) {
    // phase 1: greedy descent on arrangement distance
    let s = st; let n1 = 0; let t1 = 0;
    while (permDist.get(permKey(s)) > 0) {
      const d0 = permDist.get(permKey(s));
      const g = gens.find((g2) => permDist.get(permKey(apply(s, g2.perm))) === d0 - 1);
      s = apply(s, g.perm); n1++; t1 += g.len;
    }
    const n2 = twistDist.get(key(s));
    if (n2 === undefined) throw new Error('twist state not reachable');
    let t2 = 0;
    while (twistDist.get(key(s)) > 0) {
      const d0 = twistDist.get(key(s));
      const g = twistGens.find((g2) => twistDist.get(key(apply(s, g2.perm))) === d0 - 1);
      s = apply(s, g.perm); t2 += g.len;
    }
    if (!five.every((p) => isHome(s, p))) throw new Error('not solved');
    turns += t1 + t2;
    const tot = n1 + n2; totals[`${n1}+${n2}`] = (totals[`${n1}+${n2}`] ?? 0) + 1;
    worst = Math.max(worst, tot); sum += tot;
  }
  console.log(`\n${n}: two phases over all ${seenPos.size} positions: mean ${(sum / seenPos.size).toFixed(2)} algorithms (mean ${(turns / seenPos.size).toFixed(1)} turns, setups included), worst ${worst}; every position solved; movers+twists: ${JSON.stringify(Object.fromEntries(Object.entries(totals).sort()))}`);
}
const tw2 = bfs(twistGens, key);
console.log(`twists alone (now including UFR via R' setup): ${tw2.size} of 81; ${hist(tw2)}`);
