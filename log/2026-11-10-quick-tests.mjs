// Quick tests for the Orozco (B) and helper P shortcuts (owner 2026-11-10), checked here and written for the pages.
// Level 1: a letter one turn from the helper's place (P: L D, T D', H D2; B: O B, E B', X B2). Works with ANY other
// letter (checked): that turn, then the other letter's usual setup from where it now is, then its base.
// Level 2: a letter one turn from a level-1 spot; two turns put it in the helper's place, and the other letter must end
// on a base position (P: A L H; B: O H L) - only 2-3 partners each. Every commutator below is checked.
//   node log/2026-11-10-quick-tests.mjs           checks; prints ALL OK
//   node log/2026-11-10-quick-tests.mjs --write   also writes data/orozco-quick.js
import { writeFileSync } from 'node:fs';
import { permOf, spotOf, letterAt, expandBrackets } from './three-style-lib.mjs';
import { orozcoP } from '../data/orozco-p.js';
import { orozcoCorners } from '../data/orozco-corners.js';
const fails = []; const check = (n, ok) => { if (!ok) fails.push(n); };
const C = spotOf('C'); const to = (alg, l) => letterAt.get(permOf(alg)[spotOf(l)]);
const cyc = (a) => { const p = permOf(expandBrackets(a)); const x = p[C], y = p[x]; return p[y] === C && p.filter((v, i) => v !== i).length === 9 ? letterAt.get(x) + letterAt.get(y) : null; };
const corner = { A: 'AER', B: 'BNQ', C: 'CJM', D: 'DFI', U: 'UGL', V: 'VKP', W: 'WOT', X: 'XHS' }; const cOf = (l) => Object.keys(corner).find((k) => corner[k].includes(l));
const swap = (c) => { const [x, y] = c.slice(1, -1).split(' , '); return `[${y} , ${x}]`; };
const ALL = [...'ABDEFGHIKLNOPQRSTUVWX'];
const HELPERS = {
  P: { quick: { L: 'D', T: "D'", H: 'D2' }, pre: ['L', "L'", 'L2', 'B', "B'", 'B2'],
    row: Object.fromEntries(orozcoP.map((r) => [r.letter, { setup: r.setup, fwd: r.forwards.replace(/^\[[^:\[]+ : (\[.*\])\]$/, '$1') }])) },
  B: { quick: { O: 'B', E: "B'", X: 'B2' }, pre: ['L', "L'", 'L2', 'D', "D'", 'D2'],
    row: Object.fromEntries(orozcoCorners.map((r) => [r.letter, { setup: r.setup, fwd: `[R ${r.base} R' , U']` }])) },
};
const out = {};
for (const [h, H] of Object.entries(HELPERS)) {
  const level1 = [];
  for (const [z, t] of Object.entries(H.quick)) {
    let n = 0;
    for (const y of ALL) { if (y === h || y === z || cOf(y) === cOf(z)) continue;
      const y2 = to(t, y); const r = H.row[y2]; check(`${h} level 1 ${z}${y}: ${y} lands on ${y2}`, !!r); if (!r) continue;
      const s = [t, r.setup].filter(Boolean).join(' ');
      check(`${h} ${y}${z}`, cyc(`[${s} : ${r.fwd}]`) === y + z); check(`${h} ${z}${y}`, cyc(`[${s} : ${swap(r.fwd)}]`) === z + y); n++; }
    level1.push({ letter: z, turn: t, partners: n });
  }
  const level2 = [];
  for (const z of ALL) for (const t of H.pre) { const q = to(t, z); if (!H.quick[q] || H.quick[z]) continue;
    const s = `${t} ${H.quick[q]}`; check(`${h} ${z} reaches the helper's place`, to(s, z) === h);
    const partners = [];
    for (const y of ALL) { if (y === h || cOf(y) === cOf(z) || cOf(y) === cOf(h)) continue; const y2 = to(s, y); const r = H.row[y2]; if (!r || r.setup) continue;
      const fwd = `[${s} : ${r.fwd}]`, back = `[${s} : ${swap(r.fwd)}]`;
      check(`${h} ${y}${z}`, cyc(fwd) === y + z); check(`${h} ${z}${y}`, cyc(back) === z + y);
      partners.push({ letter: y, lands: y2, yFirst: fwd, zFirst: back }); }
    level2.push({ letter: z, first: t, onto: q, then: H.quick[q], partners });
  }
  out[h] = { level1, level2 };
  console.log(h, 'level 1', level1.map((x) => `${x.letter}:${x.partners}`).join(' '), '| level 2', level2.map((x) => `${x.letter}(${x.first}) ${x.partners.map((p) => p.letter).join('')}`).join(', '));
}
if (process.argv.includes('--write') && !fails.length) {
  writeFileSync(new URL('../data/orozco-quick.js', import.meta.url), `// BEGIN GENERATED\n// GENERATED by log/2026-11-10-quick-tests.mjs --write. Do not edit by hand.\n// Quick tests for the Orozco (B) and helper P shortcuts: level 1 (any partner) and level 2 (listed partners).\nexport const orozcoQuick = ${JSON.stringify(out)};\n// END GENERATED\n`);
  console.log('wrote data/orozco-quick.js');
}
console.log(fails.length ? `FAIL\n${fails.slice(0, 10).join('\n')}` : 'ALL OK');
