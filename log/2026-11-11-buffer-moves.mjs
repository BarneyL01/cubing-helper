// Buffer moves (2026-11-11, owner request): pairs where letting the setup move the buffer (the 3-Style (ours)
// commutators: R cores against a U or D turn, setups of R U D F, no B anywhere) beats the walk rule.
// 1. Hard letters: every pair with I, V, Q or U where ours is shorter than the walk rule.
// 2. Other pairs where ours cuts the setup by 2+ moves or saves 4+ moves (some of these keep the buffer still: they are
//    bases the walk rule does not have).
// 3. Hard-letter pairs where the walk rule is as short or shorter: keep the walk rule.
// Checks: every commutator is a pure corner 3-cycle buffer -> first -> second; ours and the walk rule agree on the pair.
//   node log/2026-11-11-buffer-moves.mjs           checks; prints ALL OK
//   node log/2026-11-11-buffer-moves.mjs --write   also writes data/buffer-moves.js
import { writeFileSync } from 'node:fs';
import { permOf, spotOf, letterAt, expandBrackets } from './three-style-lib.mjs';
import { threeStyleOurs } from '../data/three-style-ours.js';
import { walkPairs } from '../data/walk-rule.js';

const fails = []; const check = (n, ok) => { if (!ok) fails.push(n); };
const C = spotOf('C');
const cycOf = (alg) => { const p = permOf(expandBrackets(alg)); if (p.filter((v, i) => v !== i).length !== 9 || p[C] === C) return null; const a = p[C], b = p[a]; return p[b] === C ? letterAt.get(a) + letterAt.get(b) : null; };
const W = Object.fromEntries(walkPairs.map((p) => [p.pair, p]));
check('378 pairs in each table', threeStyleOurs.length === 378 && walkPairs.length === 378);
const HARD = /[IVQU]/;
const rows = threeStyleOurs.map((o) => {
  const w = W[o.pair];
  check(`${o.pair}: ours ${o.notation}`, cycOf(o.notation) === o.pair);
  check(`${o.pair}: walk ${w.notation}`, cycOf(w.notation) === o.pair);
  check(`${o.pair}: no B`, !/B/.test(o.notation));
  return { ...o, hard: HARD.test(o.pair), bufferMoves: o.spots.buffer !== 'C', walk: { notation: w.notation, setupMoves: w.setupMoves, count: w.count }, saves: w.count - o.count };
});
const hard = rows.filter((r) => r.hard && r.saves > 0);
const keep = rows.filter((r) => r.hard && r.saves <= 0);
const other = rows.filter((r) => !r.hard && (r.walk.setupMoves - r.setupMoves >= 2 || r.saves >= 4));
check('every hard pair placed once', hard.length + keep.length === rows.filter((r) => r.hard).length);
for (const r of [...hard, ...other]) check(`${r.pair}: reverse in the same list`, (r.hard ? hard : other).some((x) => x.pair === r.second + r.first));
const mean = (xs, f) => +(xs.reduce((a, x) => a + f(x), 0) / xs.length).toFixed(1);
const stats = {
  hard: hard.length, hardTotal: hard.length + keep.length, keep: keep.length, other: other.length,
  hardMoves: [mean(hard, (r) => r.walk.count), mean(hard, (r) => r.count)],
  otherMoves: [mean(other, (r) => r.walk.count), mean(other, (r) => r.count)],
  hardSaves2: hard.filter((r) => r.saves >= 2).length,
  otherBufferStays: other.filter((r) => !r.bufferMoves).map((r) => r.pair),
};
console.log(JSON.stringify(stats));
console.log('hard, by base:', Object.entries(hard.reduce((h, r) => ((h[`[${r.insertion} , ${r.interchange}]`] = (h[`[${r.insertion} , ${r.interchange}]`] || 0) + 1), h), {})).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', '));
console.log('other:', other.map((r) => `${r.pair} ${r.notation} (${r.walk.count} -> ${r.count}${r.bufferMoves ? '' : ', buffer stays'})`).join('; '));
console.log('keep the walk rule:', keep.map((r) => r.pair).join(' '));
if (process.argv.includes('--write') && !fails.length) {
  const out = (xs) => JSON.stringify(xs.map(({ hard: _h, ...r }) => r)).replace(/\},\{"pair"/g, '},\n{"pair"');
  writeFileSync(new URL('../data/buffer-moves.js', import.meta.url), `// BEGIN GENERATED\n// GENERATED by log/2026-11-11-buffer-moves.mjs --write. Do not edit by hand.\n// Pairs where a setup that moves the buffer (3-Style (ours) commutators) beats the walk rule.\nexport const bufferMoveStats = ${JSON.stringify(stats)};\nexport const bufferMoveHard = ${out(hard)};\nexport const bufferMoveOther = ${out(other)};\nexport const bufferMoveKeep = ${JSON.stringify(keep.map((r) => ({ pair: r.pair, walk: r.walk.notation, count: r.walk.count, ours: r.count })))};\n// END GENERATED\n`);
  console.log('wrote data/buffer-moves.js');
}
console.log(fails.length ? `FAIL (${fails.length})\n${fails.slice(0, 12).join('\n')}` : 'ALL OK');
